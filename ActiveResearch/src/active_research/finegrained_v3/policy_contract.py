TOKEN=object(); SDK=object()
FORBIDDEN={'finish','winner','winners','win','wins','top3','rank','ranking','probability',
    'probabilities','prediction','predict','predicted','score','strength','payout','results',
    'backend','raw','run','service','source','globals','getattr','eval','exec','open',
    'network','model','submit','horse_id','earned_prize','class_prize'}
def forbidden(value):
    if value in {'raw_research_cost','weighted_research_cost'}:return False
    return any(x in FORBIDDEN for x in value.lower().replace('-','_').split('_'))

def parse_source(source):
    if not isinstance(source,str) or len(source.encode())>1024**2:raise PolicyInvalid('Source size')
    try:t=ast.parse(source)
    except (SyntaxError,RecursionError) as e:raise PolicyInvalid('Syntax') from e
    functions={}
    for f in t.body:
        if not isinstance(f,ast.FunctionDef) or f.name in functions:raise PolicyInvalid('Only unique functions')
        a=f.args
        if (f.decorator_list or f.returns or a.posonlyargs or a.kwonlyargs or a.defaults or
            a.kw_defaults or a.vararg or a.kwarg or any(x.annotation for x in a.args)):
            raise PolicyInvalid('Plain function signature only')
        if f.name.startswith('_') or forbidden(f.name):raise PolicyInvalid('Forbidden helper name')
        if f.name!='collect_evidence' and any(x.arg in {'sdk','context'} for x in a.args):raise PolicyInvalid('Helper capabilities forbidden')
        functions[f.name]=f
    if 'collect_evidence' not in functions or [x.arg for x in functions['collect_evidence'].args.args]!=['sdk','context']:
        raise PolicyInvalid('Required collect_evidence(sdk, context)')
    allowed=(ast.FunctionDef,ast.arguments,ast.arg,ast.Assign,ast.For,ast.If,ast.Return,
        ast.Expr,ast.Break,ast.Continue,ast.Pass,ast.Name,ast.Load,ast.Store,ast.Constant,
        ast.List,ast.Tuple,ast.Dict,ast.Subscript,ast.Call,ast.Attribute,ast.keyword,
        ast.Compare,ast.Eq,ast.NotEq,ast.Lt,ast.LtE,ast.Gt,ast.GtE,ast.In,ast.NotIn,
        ast.Is,ast.IsNot,ast.BoolOp,ast.And,ast.Or,ast.UnaryOp,ast.Not,ast.USub,ast.UAdd,
        ast.BinOp,ast.Add,ast.Sub,ast.Mult,ast.Div,ast.FloorDiv,ast.Mod)
    graph={k:set() for k in functions}
    for name,f in functions.items():
        for n in ast.walk(f):
            if not isinstance(n,allowed):raise PolicyInvalid('Unsupported syntax: '+type(n).__name__)
            if isinstance(n,ast.FunctionDef) and n is not f:raise PolicyInvalid('No nested functions')
            if isinstance(n,ast.Name) and (n.id.startswith('_') or forbidden(n.id)):raise PolicyInvalid('Forbidden identifier')
            if isinstance(n,ast.Constant) and isinstance(n.value,str) and forbidden(n.value):raise PolicyInvalid('Predictive/internal field forbidden')
            if isinstance(n,ast.Assign) and (len(n.targets)!=1 or not isinstance(n.targets[0],ast.Name)
                or n.targets[0].id in {'sdk','context'}|set(functions)):
                raise PolicyInvalid('Only local immutable bindings')
            if isinstance(n,ast.For) and (not isinstance(n.target,ast.Name) or n.target.id in {'sdk','context'}|set(functions)):
                raise PolicyInvalid('Local loop binding only')
            if isinstance(n,ast.Attribute) and n.attr not in {'call','state','package','stop_horse','stop_domain','get'}:
                raise PolicyInvalid('No object access')
            if isinstance(n,ast.Call):
                if isinstance(n.func,ast.Name):
                    if n.keywords or n.func.id not in {'len','range','sorted','min','max','abs'}|set(functions):raise PolicyInvalid('Unknown callable')
                    if n.func.id in functions:
                        graph[name].add(n.func.id)
                        if n.func.id=='collect_evidence':raise PolicyInvalid('No capability recursion')
                        if len(n.args)!=len(functions[n.func.id].args.args):raise PolicyInvalid('Helper arity')
                    if any(isinstance(x,ast.Name) and x.id=='sdk' for x in n.args):raise PolicyInvalid('No SDK escape')
                elif isinstance(n.func,ast.Attribute):
                    method=n.func.attr
                    if method=='get':
                        if n.keywords or not 1<=len(n.args)<=2:raise PolicyInvalid('get arity')
                    else:
                        if name!='collect_evidence' or not isinstance(n.func.value,ast.Name) or n.func.value.id!='sdk':raise PolicyInvalid('SDK root only')
                        if method=='call':
                            if len(n.args)!=1 or not isinstance(n.args[0],ast.Constant) or n.args[0].value not in SUPPORTED:raise PolicyInvalid('Four literal domains only')
                            domain=n.args[0].value; keys=[x.arg for x in n.keywords]
                            if set(keys)!=(set() if domain=='track_context' else {'horse_number'}) and not (domain=='recent_history' and set(keys)=={'horse_number','depth'}):raise PolicyInvalid('Query arguments')
                            if len(keys)!=len(set(keys)):raise PolicyInvalid('Duplicate arguments')
                            for k in n.keywords:
                                if k.arg=='depth' and isinstance(k.value,ast.Constant) and (type(k.value.value) is not int or k.value.value not in (1,3,5)):raise PolicyInvalid('Bounded history depth')
                        elif method in {'state','stop_horse'}:
                            if n.keywords or len(n.args) not in ((0,1) if method=='state' else (1,)):raise PolicyInvalid('SDK arity')
                        elif method=='stop_domain':
                            if n.keywords or len(n.args)!=2 or not isinstance(n.args[0],ast.Constant) or n.args[0].value not in SUPPORTED:raise PolicyInvalid('Stop domain')
                        elif n.args or n.keywords:raise PolicyInvalid('Package arguments')
                else:raise PolicyInvalid('No dynamic callable')
            if isinstance(n,ast.Return) and name=='collect_evidence' and not (
                isinstance(n.value,ast.Call) and isinstance(n.value.func,ast.Attribute) and
                isinstance(n.value.func.value,ast.Name) and n.value.func.value.id=='sdk' and n.value.func.attr=='package'):
                raise PolicyInvalid('Return only trusted package')
    def visit(k,path):
        if k in path:raise PolicyInvalid('No recursive helper cycle')
        for v in graph[k]:visit(v,path|{k})
    for k in graph:visit(k,set())
    return functions

class Flow(Exception):
    def __init__(self,kind,value=None):self.kind,self.value=kind,value

def interpret(source,card,sdk,cpu_seconds=30):
    from .policy_cpu import PolicyCPU
    functions=parse_source(source);policy_context=project_context(card);clock=PolicyCPU(cpu_seconds);steps=0
    def tick():
        nonlocal steps
        steps+=1
        if steps>100000 or clock.exceeds():raise PolicyRuntimeError('Interpreter engineering limit')
    def bounded(v):
        if v is TOKEN or v is SDK:return v
        try:
            if len(packed(v))>1024**2:raise PolicyInvalid('Temporary memory bound')
        except (RecursionError,ValueError,TypeError) as e:raise PolicyInvalid('Finite JSON temporaries only') from e
        return v
    def expr(n,env):
        tick()
        if isinstance(n,ast.Constant):return n.value
        if isinstance(n,ast.Name):return env[n.id]
        if isinstance(n,(ast.List,ast.Tuple)):return bounded([expr(x,env) for x in n.elts])
        if isinstance(n,ast.Dict):return bounded({expr(k,env):expr(v,env) for k,v in zip(n.keys,n.values)})
        if isinstance(n,ast.Subscript):return expr(n.value,env)[expr(n.slice,env)]
        if isinstance(n,ast.UnaryOp):
            v=expr(n.operand,env)
            return not v if isinstance(n.op,ast.Not) else -v if isinstance(n.op,ast.USub) else +v
        if isinstance(n,ast.BinOp):
            a,b=expr(n.left,env),expr(n.right,env)
            if type(a) not in (int,float) or type(b) not in (int,float) or abs(a)>1e12 or abs(b)>1e12:raise PolicyInvalid('Bounded numeric arithmetic only')
            fs={ast.Add:lambda:a+b,ast.Sub:lambda:a-b,ast.Mult:lambda:a*b,ast.Div:lambda:a/b,ast.FloorDiv:lambda:a//b,ast.Mod:lambda:a%b}
            return bounded(fs[type(n.op)]())
        if isinstance(n,ast.BoolOp):
            for v in n.values:
                x=expr(v,env)
                if isinstance(n.op,ast.And) and not x or isinstance(n.op,ast.Or) and x:return x
            return x
        if isinstance(n,ast.Compare):
            a=expr(n.left,env)
            for op,bn in zip(n.ops,n.comparators):
                b=expr(bn,env);fs={ast.Eq:lambda:a==b,ast.NotEq:lambda:a!=b,ast.Lt:lambda:a<b,ast.LtE:lambda:a<=b,ast.Gt:lambda:a>b,ast.GtE:lambda:a>=b,ast.In:lambda:a in b,ast.NotIn:lambda:a not in b,ast.Is:lambda:a is b,ast.IsNot:lambda:a is not b}
                if not fs[type(op)]():return False
                a=b
            return True
        if isinstance(n,ast.Call):
            args=[expr(x,env) for x in n.args];kw={x.arg:expr(x.value,env) for x in n.keywords}
            if isinstance(n.func,ast.Name):
                name=n.func.id
                if name in functions:return invoke(name,args)
                if name=='range':
                    v=range(*args)
                    if len(v)>64:raise PolicyInvalid('Bounded range only')
                    return list(v)
                if name=='sorted' and (len(args)!=1 or not isinstance(args[0],(list,tuple,dict))):raise PolicyInvalid('Bounded sort')
                return bounded({'len':len,'sorted':sorted,'min':min,'max':max,'abs':abs}[name](*args))
            method=n.func.attr
            if method=='get':
                v=expr(n.func.value,env)
                if not isinstance(v,dict):raise PolicyInvalid('get needs dictionary')
                return copy.deepcopy(v.get(*args))
            if expr(n.func.value,env) is not SDK:raise PolicyInvalid('SDK binding')
            if method=='package':return TOKEN
            # The interpreter exposes methods individually, never a Python object.
            if method=='state':return clock.trusted(lambda:copy.deepcopy(sdk.state(*args)))
            if method=='call':return clock.trusted(lambda:copy.deepcopy(sdk.call(*args,**kw)))
            if method=='stop_horse':clock.trusted(lambda:sdk.stop_horse(*args));return None
            if method=='stop_domain':clock.trusted(lambda:sdk.stop_domain(*args));return None
        raise PolicyInvalid('Unsupported expression')
    def block(nodes,env):
        for n in nodes:
            tick()
            if isinstance(n,ast.Assign):env[n.targets[0].id]=bounded(expr(n.value,env))
            elif isinstance(n,ast.Expr):expr(n.value,env)
            elif isinstance(n,ast.If):block(n.body if expr(n.test,env) else n.orelse,env)
            elif isinstance(n,ast.For):
                seq=expr(n.iter,env)
                if not isinstance(seq,(list,tuple,dict)) or len(seq)>64:raise PolicyInvalid('Bounded loop container')
                broken=False
                for v in seq:
                    env[n.target.id]=copy.deepcopy(v)
                    try:block(n.body,env)
                    except Flow as e:
                        if e.kind=='break':broken=True;break
                        if e.kind!='continue':raise
                if not broken:block(n.orelse,env)
            elif isinstance(n,ast.Return):raise Flow('return',expr(n.value,env))
            elif isinstance(n,ast.Break):raise Flow('break')
            elif isinstance(n,ast.Continue):raise Flow('continue')
    def invoke(name,args):
        env={a.arg:copy.deepcopy(v) for a,v in zip(functions[name].args.args,args)}
        if name=='collect_evidence':env={'sdk':SDK,'context':policy_context}
        try:block(functions[name].body,env)
        except Flow as f:
            if f.kind=='return':return f.value
            raise PolicyInvalid('Break outside loop')
        return None
    try:
        value=invoke('collect_evidence',[])
        if value is not TOKEN:raise PolicyInvalid('Missing trusted package return')
        tick()
        return clock.trusted(sdk.package)
    except (KeyError,IndexError,TypeError,ValueError,ZeroDivisionError,OverflowError) as e:
        raise PolicyInvalid('Invalid information-state computation: '+type(e).__name__) from e
    finally:sdk.interpreter_timing=clock.snapshot(steps)

class SyntheticSDK:
    """Generated quality fixtures; no predictor values or hidden backend."""
    def __init__(self,card,variant=0):
        self.card=card;self.variant=variant;self.records=[];self.entries=[];self.events=[];self.stops=set();self.domain_stops=set()
    def state(self,number=None):
        s=information_state(self.card,self.entries,self.events,self.stops)
        return s if number is None else s['runners'][number]
    def call(self,domain,**args):
        from .domains import backend,project
        from .policy_executor import validate_action
        action=validate_action(domain,args,self.card,self.records,self.stops,self.domain_stops)
        if len(self.records)>=64:raise PolicyInvalid('Original strategy calls bound')
        n=args.get('horse_number'); depth=args.get('depth',5)
        native={'next_cursor':self.variant==1}
        if domain in {'recent_history','condition_stats'}:
            count=min(depth if domain=='recent_history' else 5, (0,5,2)[self.variant])
            obs={'horse_number':n,'starts':[{'day_index':-i-1,'race_facts':{'surface':None,'distance':None},'runner_facts':{},'values':None,'missing':None,'race_id':'synthetic','label_scope':'initial'} for i in range(count)],'scope':'latest five earlier starts; released labels only'} if domain=='recent_history' else {'horse_number':n,'groups':[],'sample_starts':count,'labelled_starts':0,'scope':'synthetic'}
        elif domain=='training':obs={'training':{'early_time':None},'feature_asof':self.card['feature_asof'],'horse_number':n,'missing':{},'billing_scope':'synthetic'}
        else:obs={'facts':{},'missing':{},'feature_asof':self.card['feature_asof']}
        record={'domain':domain,'arguments':args,'observation':obs,'provenance':digest(action),'receipt':{'total_micro':250000,'charged_cells':0}}
        self.records.append(record);self.entries.append((action,obs,native));self.events.append({'cost':record['receipt']})
        return self.state(n)
    def stop_horse(self,n):
        if n not in self.state()['runners']:raise PolicyInvalid('Foreign runner stop')
        self.stops.add(n)
    def stop_domain(self,d,n):
        if d not in SUPPORTED or n not in self.state()['runners'] or d=='track_context':raise PolicyInvalid('Invalid domain stop')
        self.domain_stops.add((d,n))
    def package(self):
        if sum(r['domain']=='track_context' for r in self.records)!=1:raise PolicyInvalid('Exactly one track_context required')
        return {'schema':'evidence-package-v1','race_id':self.card['race_id'],'entrants':[r['number'] for r in self.card['runners']],'observations':copy.deepcopy(self.records)}

def validate_source(source):
    parse_source(source);cases=[]
    for card in synthetic_cards():
        for variant in range(3):
            results=[interpret(source,card,SyntheticSDK(card,variant)) for _ in range(2)]
            if packed(results[0])!=packed(results[1]):raise PolicyInvalid('Nondeterministic')
            cases.append({'field_size':len(card['runners']),'quality_variant':variant,'tool_calls':len(results[0]['observations']),'package_digest':digest(results[0])})
    return {'valid':True,'policy_hash':source_hash(source),'validation':'information-state-synthetic-v3','deterministic':True,'zero_llm':True,'cases':cases}
